"""List the server->client messages the client understands but the server never sends.

Reads the message table in docs/ZONE_MESSAGES.md, scans server/*.py for the ids they mention,
and prints the rest grouped by the client dispatcher (subsystem) that handles them, with a
category from tools/unsent_notes.json (hand-kept) or an automatic guess. Run from the repository
root:

    python tools/unsent_messages.py > docs/UNSENT_MESSAGES.md

Categories: needed (a feature gap), variant (another form of a message the server already sends),
debug (GM, debug or test output), content (only meaningful with server content we lack), no-op
(the client ignores it), blocked (needs a UI the shipped client lacks), review (not looked at yet).
Uses only the Python standard library.
"""
import collections
import glob
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, "docs", "ZONE_MESSAGES.md")
NOTES = os.path.join(ROOT, "tools", "unsent_notes.json")
ROW = re.compile(r"\| (0x[0-9a-f]+) \| ([^|]*)\| ([^|]*)\| ([^|]*)\| ([^|]*)\|(.*)\|\s*$")


def known_messages():
    rows = {}
    with open(DOC, encoding="utf-8") as f:
        for line in f:
            m = ROW.match(line)
            if m:
                rows[int(m.group(1), 16)] = [x.strip() for x in m.groups()[1:]]
    return rows


def server_ids():
    ids = set()
    for fn in glob.glob(os.path.join(ROOT, "server", "*.py")):
        if os.path.basename(fn).startswith("test_"):
            continue
        with open(fn, encoding="utf-8") as f:
            ids.update(int(h, 16) for h in re.findall(r"0x[0-9a-fA-F]+", f.read()))
    return ids


def auto_category(row):
    detail = row[4]
    if "handled inline: return" in detail:
        return "no-op", "the dispatcher returns at once"
    if re.search(r"\bDEBUG\b|Debug:", detail):
        return "debug", ""
    return "review", ""


def main():
    rows = known_messages()
    sent = server_ids()
    notes = {}
    if os.path.exists(NOTES):
        with open(NOTES, encoding="utf-8") as f:
            data = json.load(f)
        notes = {int(k, 16): v for k, v in data.get("messages", {}).items()}
        subsystems = data.get("subsystems", {})
    else:
        subsystems = {}
    unsent = {i: r for i, r in rows.items() if i not in sent}
    groups = collections.defaultdict(list)
    for i, r in unsent.items():
        groups[r[0]].append(i)
    cats = collections.Counter()
    body = []
    for disp, ids in sorted(groups.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        name = subsystems.get(disp, "")
        body.append(f"\n## {disp}{' (' + name + ')' if name else ''}: {len(ids)}\n")
        body.append("| Id | Class | Payload | Category | Notes |\n|---|---|---|---|---|")
        for i in sorted(ids):
            r = unsent[i]
            cat, note = notes.get(i) or auto_category(r)
            if not note:
                note = re.sub(r"^strings: ", "", r[4])[:120]
            cats[cat] += 1
            body.append(f"| 0x{i:x} | {r[1]} | {r[3]} | {cat} | {note.replace('|', '/')} |")
    total = len(rows)
    print("# Server messages the server never sends\n")
    print("Generated by `tools/unsent_messages.py` from docs/ZONE_MESSAGES.md and server/*.py; categories "
          "come from tools/unsent_notes.json. Regenerate after adding a message or a note.\n")
    print(f"The client handles {total} zone messages; the server code mentions {total - len(unsent)} "
          f"of them ({100 * (total - len(unsent)) // total}%). The other {len(unsent)} by category:\n")
    print("| Category | Count |\n|---|---|")
    for c, n in cats.most_common():
        print(f"| {c} | {n} |")
    print("\n".join(body))


if __name__ == "__main__":
    main()
