"""Print the client's notice codes as a Markdown table (docs/NOTICES.md).

The server sends a notice as zone event 0x0e {i16 code}; the client's switch FUN_0061d530
maps code - 1 through a jump table at 0x61f510 to a case that pushes a localization key,
whose English text is in bin/VGClient.int. Run from the repository root (the client install):

    python tools/notice_table.py > docs/NOTICES.md

Uses only the Python standard library.
"""
import os
import re
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXE = os.path.join(ROOT, "bin", "VGClient.exe")
INI = os.path.join(ROOT, "bin", "VGClient.int")
SWITCH, TABLE, CASES = 0x61D530, 0x61F510, 0x1E3
EMPTY_STRING = 0x105FD58       # the empty wide string the cases also push


def sections(data):
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    count = struct.unpack_from("<H", data, pe + 6)[0]
    opt = struct.unpack_from("<H", data, pe + 20)[0]
    base = struct.unpack_from("<I", data, pe + 52)[0]
    out = []
    for i in range(count):
        _, vsize, va, rsize, raw = struct.unpack_from("<8sIIII", data, pe + 24 + opt + 40 * i)
        out.append((base + va, max(vsize, rsize), raw))
    return out


def reader(data):
    secs = sections(data)

    def read(addr, n):
        for va, size, raw in secs:
            if va <= addr < va + size:
                return data[raw + addr - va:raw + addr - va + n]
        return b""
    return read


def key_at(read, addr):
    raw = read(addr, 200).split(b"\0\0")[0]
    if len(raw) % 2:
        raw += b"\0"
    try:
        text = raw.decode("utf-16-le")
    except UnicodeDecodeError:
        return None
    return text if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]{2,}", text) else None


def case_key(read, addr):
    """The first localization key a case pushes (push imm32 = 0x68) before its jmp."""
    code = read(addr, 48)
    i = 0
    while i < len(code):
        op = code[i]
        if op == 0x68:
            value = struct.unpack_from("<I", code, i + 1)[0]
            if value > 0x1000000 and value != EMPTY_STRING:
                key = key_at(read, value)
                if key:
                    return key
            i += 5
        elif op == 0x6A:            # push imm8
            i += 2
        else:                       # jmp/call/anything else ends the case
            return None
    return None


def main():
    with open(EXE, "rb") as f:
        read = reader(f.read())
    text = {}
    with open(INI, encoding="latin-1") as f:
        for line in f:
            if "=" in line:
                k, v = line.split("=", 1)
                text.setdefault(k.strip(), v.strip())
    print("# Notice codes\n")
    print("Zone event 0x0e `{i16 code}` prints one of the client's own messages (`FUN_0061d530`; "
          "generated by `tools/notice_table.py` from the client's jump table and `bin/VGClient.int`). "
          "Codes without a row print something built from more data, or nothing.\n")
    print("| Code | Key | Text |")
    print("|---|---|---|")
    for code in range(1, CASES + 1):
        target = struct.unpack("<I", read(TABLE + (code - 1) * 4, 4))[0]
        key = case_key(read, target)
        if key:
            print(f"| {code} (`{code:#x}`) | `{key}` | {text.get(key, '').replace('|', '/')} |")


if __name__ == "__main__":
    main()
